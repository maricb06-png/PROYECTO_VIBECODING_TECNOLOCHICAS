DROP POLICY IF EXISTS "workspace_insert_habits" ON public.cozy_habits;
CREATE POLICY "workspace_insert_habits" ON public.cozy_habits FOR INSERT TO anon, authenticated WITH CHECK (true);
DROP POLICY IF EXISTS "workspace_update_habits" ON public.cozy_habits;
CREATE POLICY "workspace_update_habits" ON public.cozy_habits FOR UPDATE TO anon, authenticated USING (true) WITH CHECK (true);
DROP POLICY IF EXISTS "workspace_delete_habits" ON public.cozy_habits;
CREATE POLICY "workspace_delete_habits" ON public.cozy_habits FOR DELETE TO anon, authenticated USING (true);

