/*
# Create Cozy Life core workspace

1. New tables
- `cozy_tasks`: personal tasks with scheduling, priority, category, duration, status, and XP value.
- `cozy_habits`: recurring habits with streak tracking and a weekly completion count.
- `cozy_notes`: quick notes with optional category, pinning, and timestamps.
2. Security
- RLS is enabled on every table.
- The app is intentionally single-tenant with no sign-in screen, so anon and authenticated roles can use the workspace.
- Four separate CRUD policies are created for each table.
3. Data integrity
- UUID identifiers and timestamp defaults are generated by PostgreSQL.
- Status and priority fields use safe defaults and constrained values.
*/

CREATE TABLE IF NOT EXISTS public.cozy_tasks (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  title text NOT NULL,
  description text NOT NULL DEFAULT '',
  category text NOT NULL DEFAULT 'Otros',
  priority text NOT NULL DEFAULT 'media' CHECK (priority IN ('baja', 'media', 'alta', 'urgente')),
  status text NOT NULL DEFAULT 'pendiente' CHECK (status IN ('pendiente', 'en progreso', 'completada')),
  due_date date,
  start_time time,
  end_time time,
  estimated_minutes integer NOT NULL DEFAULT 30 CHECK (estimated_minutes > 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  completed_at timestamptz
);

CREATE TABLE IF NOT EXISTS public.cozy_habits (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text NOT NULL,
  icon text NOT NULL DEFAULT 'sprout',
  color text NOT NULL DEFAULT '#8FA58A',
  frequency text NOT NULL DEFAULT 'Diario',
  current_streak integer NOT NULL DEFAULT 0 CHECK (current_streak >= 0),
  completed_today boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.cozy_notes (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  title text NOT NULL,
  body text NOT NULL DEFAULT '',
  category text NOT NULL DEFAULT 'Ideas',
  color text NOT NULL DEFAULT '#F2E4A8',
  pinned boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.cozy_tasks ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.cozy_habits ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.cozy_notes ENABLE ROW LEVEL SECURITY;

GRANT SELECT, INSERT, UPDATE, DELETE ON public.cozy_tasks TO anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.cozy_habits TO anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.cozy_notes TO anon, authenticated;

DROP POLICY IF EXISTS "workspace_read_tasks" ON public.cozy_tasks;
CREATE POLICY "workspace_read_tasks" ON public.cozy_tasks FOR SELECT TO anon, authenticated USING (true);
DROP POLICY IF EXISTS "workspace_insert_tasks" ON public.cozy_tasks;
CREATE POLICY "workspace_insert_tasks" ON public.cozy_tasks FOR INSERT TO anon, authenticated WITH CHECK (true);
DROP POLICY IF EXISTS "workspace_update_tasks" ON public.cozy_tasks;
CREATE POLICY "workspace_update_tasks" ON public.cozy_tasks FOR UPDATE TO anon, authenticated USING (true) WITH CHECK (true);
DROP POLICY IF EXISTS "workspace_delete_tasks" ON public.cozy_tasks;
CREATE POLICY "workspace_delete_tasks" ON public.cozy_tasks FOR DELETE TO anon, authenticated USING (true);

DROP POLICY IF EXISTS "workspace_read_habits" ON public.cozy_habits;
